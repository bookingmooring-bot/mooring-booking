export const searchMoorings = (query: string): Mooring[] => {
  if (!query) return allMoorings;

  const lowerQuery = query.toLowerCase();
  return allMoorings.filter(
    (m) =>
      m.location.toLowerCase().includes(lowerQuery) ||
      m.country.toLowerCase().includes(lowerQuery) ||
      m.name.toLowerCase().includes(lowerQuery)
  );
};

export const getMooringsByCountry = (country: string): Mooring[] => {
  return allMoorings.filter((m) => m.country.toLowerCase() === country.toLowerCase());
};

export const getFeaturedMoorings = (): Mooring[] => {
  return allMoorings.filter((m) => m.rating >= 4.7).slice(0, 6);
};
